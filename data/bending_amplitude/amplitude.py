"""Amplitude of the bond-preserving (bending) response from existing force constants.
For every system: H (full 3N or symmetric sector embedded as S Hs S^T), drive f, linear response u = H^+ f
(and actual u).
Coordinates are split into three equivariant blocks: p = network bond-preserving (kernel of the B-X bond Jacobian,
centred), q = network bond-changing (row space, = bond tensions), A = A-cation displacements.
Reported:
  shares        drive / predicted / actual bond-preserving share (definitions of bending_enrichment/enrichment_all.py)
  channels      contribution of f_q (tension), f_p, f_A to the bending of the response
  block model   u_p = K_pp^-1 (f_p - K_pq u_q - K_pA u_A): amplitude ratio |u_p|/|u_q| = softness x coupling
  stiffness     mean Rayleigh quotients of K_pp, K_qq and the normalised coupling
  local         B-X bond lengths by B species (size mismatch), within-octahedron bond spread, bridge-angle spread
Reads the force constants of the neighbouring folders (paths below); writes amplitude.json and prints a summary table.
usage: python amplitude.py"""
import json
from pathlib import Path

import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
DATA_DIR = SCRIPT_DIR.parents[0]
FORCE_BALANCE_DIR = DATA_DIR / "force_balance_reference"
TIGHT_FORCE_BALANCE_DIR = DATA_DIR / "spinel_pressure_path" / "force_balance"
FULL_FORCE_BALANCE_DIR = DATA_DIR / "bending_enrichment" / "full_force_balance"
SECTOR_FORCE_BALANCE_DIR = DATA_DIR / "bending_enrichment" / "sector_force_balance"
AMPLITUDE_SECTOR_DIR = SCRIPT_DIR / "sector_force_balance"


def full_H(read_forces, N, delta):
    H = np.zeros((3 * N, 3 * N))
    for i in range(N):
        for a, ax in enumerate("xyz"):
            H[3 * i + a] = -(read_forces(f"d{i:02d}{ax}p") - read_forces(f"d{i:02d}{ax}m")).ravel() / (2 * delta)
    return 0.5 * (H + H.T)


def translation_basis(N):
    T = np.zeros((3 * N, 3))
    for a in range(3):
        T[a::3, a] = 1 / np.sqrt(N)
    return T


def orthonormal_columns(M, tol=1e-8):
    U, s, _ = np.linalg.svd(M, full_matrices=False)
    return U[:, s > tol * max(s[0], 1e-30)] if len(s) else M


def analyse(name, topo, L, f1, f2, species, bonds, net, H, Sbasis, f0, interval):
    N = len(species)
    species = np.array(species)
    net = np.array(net)
    net_column = {int(a): c for c, a in enumerate(net)}
    bond_vectors = np.array([(f1[j] - f1[i] + np.array(img)) @ L for i, j, img in bonds])
    J = np.zeros((len(bonds), 3 * len(net)))
    for r, (i, j, _) in enumerate(bonds):
        e = bond_vectors[r] / np.linalg.norm(bond_vectors[r])
        J[r, 3 * net_column[i]:3 * net_column[i] + 3] = -e
        J[r, 3 * net_column[j]:3 * net_column[j] + 3] = e
    _, s, Vt = np.linalg.svd(J, full_matrices=False)
    bond_basis = Vt[: int(np.sum(s > s[0] * 1e-10))]
    nidx = np.concatenate([[3 * a, 3 * a + 1, 3 * a + 2] for a in net])
    aidx = np.setdiff1d(np.arange(3 * N), nidx)

    def blocks(x):
        x = np.asarray(x, float)
        xn = x[nidx].reshape(-1, 3)
        xn = (xn - xn.mean(axis=0)).ravel()
        q = bond_basis.T @ (bond_basis @ xn)
        p = xn - q
        P = np.zeros(3 * N)
        Qv = np.zeros(3 * N)
        A = np.zeros(3 * N)
        P[nidx] = p
        Qv[nidx] = q
        A[aidx] = x[aidx]
        return P, Qv, A

    def share(x):
        p, q, _ = blocks(x)
        return float(p @ p / (p @ p + q @ q))

    # sector bases for the three blocks
    Bp = orthonormal_columns(np.column_stack([blocks(c)[0] for c in Sbasis.T]))
    Bq = orthonormal_columns(np.column_stack([blocks(c)[1] for c in Sbasis.T]))
    Ba = np.column_stack([blocks(c)[2] for c in Sbasis.T])
    Ba = orthonormal_columns(Sbasis @ (Sbasis.T @ Ba))  # A block without net translation
    leak = max(float(np.linalg.norm(B - Sbasis @ (Sbasis.T @ B))) for B in (Bp, Bq, Ba) if B.size)
    G = Sbasis @ np.linalg.pinv(Sbasis.T @ H @ Sbasis) @ Sbasis.T
    T = translation_basis(N)
    f0 = f0 - T @ (T.T @ f0)
    u = G @ f0
    fp, fq, fa = blocks(f0)
    up_tot = blocks(u)[0]
    channels = {}
    for k, fx in (("tension_f_q", fq), ("bending_f_p", fp), ("A_cation_f_A", fa)):
        b = blocks(G @ fx)[0]
        channels[k] = float(b @ up_tot / (up_tot @ up_tot)) if up_tot @ up_tot > 0 else None
    ua = blocks(u)
    Kpp = Bp.T @ H @ Bp
    Kpq = Bp.T @ H @ Bq
    KpA = Bp.T @ H @ Ba if Ba.size else np.zeros((Bp.shape[1], 0))
    Kqq = Bq.T @ H @ Bq
    cq, ca = Bq.T @ ua[1], (Ba.T @ ua[2] if Ba.size else np.zeros(0))
    g = Kpq @ cq + KpA @ ca  # force on p generated by the q and A response
    up_model = np.linalg.solve(Kpp, Bp.T @ fp - g)
    # direct-drive and coupling-generated bending
    ud, ug = np.linalg.solve(Kpp, Bp.T @ fp), np.linalg.solve(Kpp, -g)
    wpp = np.linalg.eigvalsh(Kpp)
    wqq = np.linalg.eigvalsh(Kqq)
    nq = np.linalg.norm(cq)
    wv, Vv = np.linalg.eigh(Kpp)
    cp = Vv.T @ (Bp.T @ ua[0])
    wt = cp ** 2 / (cp @ cp)  # bending response by K_pp mode
    cf = Vv.T @ (Bp.T @ fp)
    cg = Vv.T @ g
    order = np.argsort(-wt)
    cum = np.cumsum(wt[order])
    modes = [{"k": float(wv[i]), "weight_in_up": float(wt[i]), "f_p_comp": float(cf[i]),
              "coupling_comp": float(-cg[i])} for i in order[:4]]
    out = {"system": name, "topology": topo, "interval_GPa": interval, "n_atoms": N,
           "dim_p_q_A_in_sector": [Bp.shape[1], Bq.shape[1], Ba.shape[1]], "sector_leak": leak,
           "drive_share": share(f0), "predicted_share": share(u),
           "channels_of_bending": channels,
           "amplitude_ratio_up_over_uq": float(np.linalg.norm(Bp.T @ ua[0]) / nq),
           "model_check_up": float(np.linalg.norm(up_model - Bp.T @ ua[0]) / np.linalg.norm(Bp.T @ ua[0])),
           "coupling_force_per_uq_eV_A2": float(np.linalg.norm(Kpq @ cq) / nq),
           "A_coupling_force_per_uq_eV_A2": float(np.linalg.norm(KpA @ ca) / nq) if ca.size else 0.0,
           "block_direct_up_per_uq": float(np.linalg.norm(ud) / nq),
           "block_coupling_up_per_uq": float(np.linalg.norm(ug) / nq),
           "block_coupling_fraction_of_up": float(ug @ up_model / (up_model @ up_model)),
           "block_force_ratio_coupling_over_direct": float(np.linalg.norm(g) / max(np.linalg.norm(Bp.T @ fp), 1e-30)),
           "softness_gain_A2_per_eV": float(np.linalg.norm(np.linalg.solve(Kpp, g)) / np.linalg.norm(g)),
           "k_pp_mean": float(wpp.mean()), "k_pp_min": float(wpp.min()), "k_qq_mean": float(wqq.mean()),
           "coupling_norm_rel": float(np.linalg.norm(Kpq, 2) / np.sqrt(wpp.max() * wqq.max())),
           "uq_rms_A": float(nq / np.sqrt(len(net))), "top_bending_modes": modes,
           "n_modes_80pct": int(np.searchsorted(cum, 0.8) + 1), "weight_k_below_1": float(wt[wv < 1].sum()),
           "f_tension_norm": float(np.linalg.norm(fq))}
    if f2 is not None:
        df = f2 - f1
        df -= np.round(df)
        ux = (df @ L).ravel()
        ux -= T @ (T.T @ ux)
        out["actual_share"] = share(ux)
    # local descriptors at the start structure
    lengths_by_species = {}
    lengths_per_octahedron = {}
    for (i, j, _), v in zip(bonds, bond_vectors):
        b = i  # bonds are stored as (B, X, image)
        lengths_by_species.setdefault(str(species[b]), []).append(float(np.linalg.norm(v)))
        lengths_per_octahedron.setdefault(int(b), []).append(float(np.linalg.norm(v)))
    means = {k: float(np.mean(v)) for k, v in lengths_by_species.items()}
    mean_lengths = list(means.values())
    out["BX_mean_by_species_A"] = means
    out["size_mismatch"] = (float((max(mean_lengths) - min(mean_lengths)) / np.mean(mean_lengths))
                            if len(mean_lengths) > 1 else 0.0)
    out["intra_oct_spread"] = float(np.mean([np.std(v) / np.mean(v) for v in lengths_per_octahedron.values()]))
    bridge_angles = []
    ligand_bonds = {}
    for (i, j, img), v in zip(bonds, bond_vectors):
        ligand_bonds.setdefault(j, []).append((i, -v))  # X j sees B i along -v
    for xj, lst in ligand_bonds.items():
        for a in range(len(lst)):
            for b in range(a + 1, len(lst)):
                c = lst[a][1] @ lst[b][1] / np.linalg.norm(lst[a][1]) / np.linalg.norm(lst[b][1])
                bridge_angles.append(np.degrees(np.arccos(np.clip(c, -1, 1))))
    bridge_angles = np.array(bridge_angles)
    out["bridge_angle_mean_deg"] = float(bridge_angles.mean())
    out["bridge_angle_std_deg"] = float(bridge_angles.std())
    return out


rows = []

# k12 tight 4->5 GPa: full H
meta = json.loads((TIGHT_FORCE_BALANCE_DIR / "meta.json").read_text())
species = list(np.repeat(meta["species"], meta["counts"]))
N = len(species)
H = full_H(lambda c: np.load(FORCE_BALANCE_DIR / "forces" / f"{c}.npy"), N, meta["delta_A"])
bonds = json.loads((FORCE_BALANCE_DIR / "inputs" / "pressure_bond_accommodation.json").read_text())["bonds"]
net = list(np.flatnonzero(np.isin(species, ["Sc", "Sb", "Se"])))
T = translation_basis(N)
Sfull = orthonormal_columns(np.eye(3 * N) - T @ T.T)
rows.append(analyse("MgSc0.5Sb1.5Se4 k12", "edge", np.array(meta["lattice_5GPa"]), np.array(meta["frac_start"]),
                    np.array(meta["frac_5GPa"]), species, bonds, net, H, Sfull,
                    np.load(TIGHT_FORCE_BALANCE_DIR / "forces" / "ref.npy").ravel(), "4-5"))

# corner-sharing CaTiO3, CaSnO3: full H
for system, case_name in (("CaTiO3", "ca_tio3"), ("CaSnO3", "ca_sno3")):
    case_dir = FULL_FORCE_BALANCE_DIR / case_name / "p0_p5"
    meta = json.loads((case_dir / "meta.json").read_text())
    species = list(np.repeat(meta["species"], meta["counts"]))
    N = len(species)

    def read_forces(c):
        return np.load(case_dir / "hessian" / c / "forces.npy")

    H = full_H(read_forces, N, meta["delta_A"])
    bonds = meta["bonds"]
    net = sorted({b[0] for b in bonds} | {b[1] for b in bonds})
    T = translation_basis(N)
    Sfull = orthonormal_columns(np.eye(3 * N) - T @ T.T)
    rows.append(analyse(system, "corner", np.array(meta["lattice_P2"]), np.array(meta["frac_start"]),
                        np.array(meta["frac_P2"]), species, bonds, net, H, Sfull, read_forces("ref").ravel(), "0-5"))

# symmetric-sector systems
for sector_root, system, label, topo in (
        (SECTOR_FORCE_BALANCE_DIR, "spinel_k08", "MgScSbSe4 k08", "edge"),
        (AMPLITUDE_SECTOR_DIR, "spinel_cd_ga_ino4", "Cd(Ga,In)2O4", "edge"),
        (AMPLITUDE_SECTOR_DIR, "layered_na_sc_ino2", "Na(Sc,In)O2 layered", "edge"),
        (AMPLITUDE_SECTOR_DIR, "spinel_k12_tight", "k12 tight 0-5 GPa", "edge"),
        (SECTOR_FORCE_BALANCE_DIR, "ca2_sn_tio6_rs", "Ca2SnTiO6", "corner"),
        (SECTOR_FORCE_BALANCE_DIR, "ca8_sn6_ti2o24", "Ca8Sn6Ti2O24", "corner")):
    case_dir = sector_root / system / "p0_p5"
    meta = json.loads((case_dir / "meta.json").read_text())
    S = np.load(case_dir / "S.npy")
    species = list(np.repeat(meta["species"], meta["counts"]))
    N = len(species)
    delta = meta["delta_A"]

    def read_forces(c):
        return np.load(case_dir / "hessian" / c / "forces.npy").ravel()

    ns = S.shape[1]
    Hs = np.zeros((ns, ns))
    for k in range(ns):
        Hs[k] = -(S.T @ (read_forces(f"s{k:03d}p") - read_forces(f"s{k:03d}m"))) / (2 * delta)
    Hs = 0.5 * (Hs + Hs.T)
    rows.append(analyse(label, topo, np.array(meta["lattice_P2"]), np.array(meta["frac_start"]),
                        np.array(meta["frac_P2"]), species, meta["bonds"], meta["network"], S @ Hs @ S.T, S,
                        read_forces("ref"), "0-5"))

(SCRIPT_DIR / "amplitude.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False), encoding="utf-8")
hdr = ("system                 topo   drive%  pred%  act%   |up|/|uq|  tension-ch  A-ch   coupl/uq  soft-gain  "
       "k_pp  k_pp_min k_qq  mism   oct-spr  ang-std leak")
print(hdr)
