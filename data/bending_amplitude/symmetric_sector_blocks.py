"""Block model of the bending response with the blocks taken inside the symmetric sector.
amplitude.py projects symmetric-sector vectors onto the bond-preserving space; that fails when the bond projector
does not commute with the sector projector (k12 0-5 GPa, Cm: leak 4.9). Here the blocks are taken inside the sector:
  p_s = {x in sector : J x_net = 0, x_A = 0}      (bond-preserving network motions available in the sector)
  c_s = orthogonal complement of p_s in the sector (bond-changing network motions and A-cation motions)
Block model u_p = K_pp^-1 (f_p - K_pc u_c); coupling fraction = share of u_p generated by -K_pp^-1 K_pc u_c.
k_pp = mean eigenvalue of K_pp. Applied identically to k12 4-5 (full H), k12 0-5 (sector) and k08 (sector).
Reads the force constants of the neighbouring folders (paths below); writes symmetric_sector_blocks.json and prints
one JSON line per system.
usage: python symmetric_sector_blocks.py"""
import json
from pathlib import Path

import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
DATA_DIR = SCRIPT_DIR.parents[0]
FORCE_BALANCE_DIR = DATA_DIR / "force_balance_reference"
TIGHT_FORCE_BALANCE_DIR = DATA_DIR / "spinel_pressure_path" / "force_balance"
SECTOR_FORCE_BALANCE_DIR = DATA_DIR / "bending_enrichment" / "sector_force_balance"
AMPLITUDE_SECTOR_DIR = SCRIPT_DIR / "sector_force_balance"


def translation_basis(N):
    T = np.zeros((3 * N, 3))
    for a in range(3):
        T[a::3, a] = 1 / np.sqrt(N)
    return T


def null_space(M, tol=1e-9):
    _, s, Vt = np.linalg.svd(M)
    r = int(np.sum(s > tol * s[0]))
    return Vt[r:].T


def block_analysis(name, L, f1, species, bonds, net, S, Hs, f0):
    N = len(species)
    species = np.array(species)
    net = np.array(net)
    J = np.zeros((len(bonds), 3 * N))
    for r, (i, j, img) in enumerate(bonds):
        v = (f1[j] - f1[i] + np.array(img)) @ L
        e = v / np.linalg.norm(v)
        J[r, 3 * i:3 * i + 3] = -e
        J[r, 3 * j:3 * j + 3] = e
    aidx = np.concatenate([[3 * a, 3 * a + 1, 3 * a + 2] for a in range(N) if a not in set(net.tolist())])
    C = np.vstack([J, np.eye(3 * N)[aidx]]) @ S  # constraints on sector coordinates
    Pp = null_space(C)  # p_s in sector coordinates
    if Pp.shape[1] == 0:
        return {"system": name, "sector_dof": S.shape[1], "dim_p_s": 0,
                "note": "no pure bond-preserving motion inside the sector"}
    Pc = null_space(Pp.T)  # complement in the sector
    Kpp = Pp.T @ Hs @ Pp
    Kpc = Pp.T @ Hs @ Pc
    a = np.linalg.solve(Hs, S.T @ f0)  # linear response in sector coordinates
    up, uc = Pp.T @ a, Pc.T @ a
    ud = np.linalg.solve(Kpp, Pp.T @ (S.T @ f0))
    ug = np.linalg.solve(Kpp, -Kpc @ uc)
    w = np.linalg.eigvalsh(Kpp)
    return {"system": name, "sector_dof": S.shape[1], "dim_p_s": Pp.shape[1], "k_pp_mean": float(w.mean()),
            "k_pp_min": float(w.min()),
            "coupling_fraction": float(ug @ up / (up @ up)), "direct_fraction": float(ud @ up / (up @ up)),
            "model_err": float(np.linalg.norm(ud + ug - up) / np.linalg.norm(up)),
            "p_s_share_of_response": float(up @ up / (a @ a))}


rows = []
meta = json.loads((TIGHT_FORCE_BALANCE_DIR / "meta.json").read_text())
species = list(np.repeat(meta["species"], meta["counts"]))
N = len(species)
delta = meta["delta_A"]
H = np.zeros((3 * N, 3 * N))
for i in range(N):
    for k, ax in enumerate("xyz"):
        H[3 * i + k] = -(np.load(FORCE_BALANCE_DIR / "forces" / f"d{i:02d}{ax}p.npy")
                         - np.load(FORCE_BALANCE_DIR / "forces" / f"d{i:02d}{ax}m.npy")).ravel() / (2 * delta)
H = 0.5 * (H + H.T)
T = translation_basis(N)
_, s, Vt = np.linalg.svd(np.eye(3 * N) - T @ T.T)
S = Vt[: 3 * N - 3].T
bonds = json.loads((FORCE_BALANCE_DIR / "inputs" / "pressure_bond_accommodation.json").read_text())["bonds"]
net = list(np.flatnonzero(np.isin(species, ["Sc", "Sb", "Se"])))
rows.append(block_analysis("k12 4-5 GPa (full H)", np.array(meta["lattice_5GPa"]), np.array(meta["frac_start"]),
                           species, bonds, net, S, S.T @ H @ S,
                           np.load(TIGHT_FORCE_BALANCE_DIR / "forces" / "ref.npy").ravel()))
for sector_root, system, label in ((AMPLITUDE_SECTOR_DIR, "spinel_k12_tight", "k12 0-5 GPa (sector)"),
                                   (SECTOR_FORCE_BALANCE_DIR, "spinel_k08", "k08 0-5 GPa (sector)"),
                                   (AMPLITUDE_SECTOR_DIR, "spinel_cd_ga_ino4", "Cd(Ga,In)2O4 (sector)"),
                                   (AMPLITUDE_SECTOR_DIR, "layered_na_sc_ino2", "Na(Sc,In)O2 (sector)")):
    case_dir = sector_root / system / "p0_p5"
    meta = json.loads((case_dir / "meta.json").read_text())
    S = np.load(case_dir / "S.npy")
    species = list(np.repeat(meta["species"], meta["counts"]))
    delta = meta["delta_A"]

    def read_forces(c):
        return np.load(case_dir / "hessian" / c / "forces.npy").ravel()

    ns = S.shape[1]
    Hs = np.zeros((ns, ns))
    for k in range(ns):
        Hs[k] = -(S.T @ (read_forces(f"s{k:03d}p") - read_forces(f"s{k:03d}m"))) / (2 * delta)
    Hs = 0.5 * (Hs + Hs.T)
    rows.append(block_analysis(label, np.array(meta["lattice_P2"]), np.array(meta["frac_start"]), species,
                               meta["bonds"], meta["network"], S, Hs, read_forces("ref")))
(SCRIPT_DIR / "symmetric_sector_blocks.json").write_text(json.dumps(rows, indent=1))
for r in rows:
    print(json.dumps(r))
